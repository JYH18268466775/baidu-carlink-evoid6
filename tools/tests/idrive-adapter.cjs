const assert = require('node:assert/strict');
const {IdriveAdapter} = require('../../src/carlife_idrive_adapter.cjs');
const a = new IdriveAdapter();
let ms = 0;
const send = event => a.accept({ms: ms++, ...event}).map(p => p.inner[9]);
const key = (key, down, extra = {}) => send({type: 'key', key, down, ...extra});
assert.deepEqual(key('OK', true), []);
send({type: 'focus', active: true});
assert.deepEqual(key('OK', false), []);
assert.deepEqual(key('OK', true), [0x14]);
assert.deepEqual(key('OK', true), []);
assert.deepEqual(key('OK', false), []);
assert.deepEqual(send({type: 'rotate', delta: -2}), [7, 7]);
assert.deepEqual(send({type: 'rotate', delta: 2}), [6, 6]);
assert.deepEqual(key('BACK', true), []);
assert.deepEqual(key('BACK', false), [14]);
key('BACK', true); ms += 800;
assert.deepEqual(key('BACK', false), []);
key('BACK', true); send({type: 'focus', active: false});
send({type: 'focus', active: true});
assert.deepEqual(key('BACK', false), []);
key('BACK', true);
assert.deepEqual(key('BACK', false, {cancel: true}), []);
send({type: 'disconnect'});
assert.deepEqual(send({type: 'rotate', delta: 1}), []);
assert.throws(() => send({type: 'rotate', delta: 32767}), /bounded/);
assert.throws(() => key('MENU', true), /Unsupported/);
assert.throws(() => a.accept({type: 'focus', active: true, ms: 0}), /monotonic/);
console.log('PASS: focus, duplicate downs, short/long BACK, cancellation, rotary bounds and disconnect');
